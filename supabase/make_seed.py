"""Generate supabase/seed.sql from observations.json (the fixed station list).

Usage (from the Pipeline folder):  .venv/bin/python supabase/make_seed.py
Then run supabase/seed.sql in the Supabase SQL editor (or `psql`) after applying the migration.
Safe to re-run: it upserts.
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
stations = json.loads((root / "observations.json").read_text())["stations"]


def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


rows = ",\n".join(f"  ({q(s['id'])}, {q(s['name'])}, {s['lat']}, {s['lon']})" for s in stations)
sql = f"""-- Generated by supabase/make_seed.py from observations.json ({len(stations)} stations). Safe to re-run.
insert into public.stations (station_id, name, lat, lon) values
{rows}
on conflict (station_id) do update
  set name = excluded.name, lat = excluded.lat, lon = excluded.lon;
"""
(root / "supabase" / "seed.sql").write_text(sql)
print(f"wrote supabase/seed.sql with {len(stations)} stations")
